def all_seo_phrases() -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for phrases in SEO_INTENT_GROUPS.values():
        for phrase in phrases:
            key = phrase.casefold()
            if key not in seen:
                seen.add(key)
                result.append(phrase)
    return result


def phrases_for_category(category_name: str) -> list[str]:
    keys = CATEGORY_INTENT_MAP.get(category_name, ('kupit',))
    seen: set[str] = set()
    result: list[str] = []
    for key in keys:
        for phrase in SEO_INTENT_GROUPS.get(key, ()):
            norm = phrase.casefold()
            if norm not in seen:
                seen.add(norm)
                result.append(phrase)
    return result


def geo_phrases() -> list[str]:
    phrases = [
        GEO_REGION,
        GEO_REGION_SHORT,
        f'купить {GEO_REGION_SHORT.lower()}',
        f'доставка {GEO_REGION.lower()}',
        f'моющие средства {GEO_REGION.lower()}',
        'купить моющие средства уссурийск',
    ]
    for city in GEO_CITIES:
        city_lower = city.lower()
        phrases.append(f'моющие средства {city_lower}')
        phrases.append(f'купить {city_lower}')
    return phrases


def product_seo_search_extras(category_name: str = '') -> str:
    """Текст для search_text — чтобы находить товары по SEO-запросам."""
    parts = list(phrases_for_category(category_name)) if category_name else all_seo_phrases()[:40]
    parts.extend(geo_phrases())
    return ' '.join(parts).casefold()


