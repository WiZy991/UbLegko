def meta_keywords_string(limit: int = 250) -> str:
    """Краткий список для meta keywords (Yandex)."""
    sample = all_seo_phrases()[:35] + [GEO_REGION, 'Уссурийск']
    text = ', '.join(sample)
    if len(text) <= limit:
        return text
    return text[: limit - 1].rsplit(',', 1)[0]
