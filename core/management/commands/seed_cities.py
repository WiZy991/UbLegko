class Command(BaseCommand):
    help = 'Загружает список городов России (по умолчанию Уссурийск)'

    def handle(self, *args, **options):
        # Сбрасываем default у всех, затем выставим Уссурийск
        City.objects.update(is_default=False)
        created = updated = 0
        for name, region, is_default, sort_order in CITIES:
            obj, was_created = City.objects.update_or_create(
                name=name,
                defaults={
                    'region': region,
                    'is_default': is_default,
                    'is_active': True,
                    'sort_order': sort_order,
                },
            )
            if was_created:
                created += 1
            else:
                updated += 1
        self.stdout.write(self.style.SUCCESS(f'Города: создано {created}, обновлено {updated}'))
